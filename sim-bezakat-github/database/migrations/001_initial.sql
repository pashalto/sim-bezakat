  id_periode_monitoring bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pengelola_kemenag bigint NOT NULL REFERENCES pengelola_kemenag ON DELETE RESTRICT,
  tahun_anggaran integer NOT NULL CHECK (tahun_anggaran BETWEEN 2000 AND 9998),
