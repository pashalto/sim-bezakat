CREATE TABLE verifikasi_laporan (
  id_verifikasi bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_laporan_bulanan bigint NOT NULL,
  nomor_pengajuan integer NOT NULL,
  tahap_verifikasi text NOT NULL CHECK (tahap_verifikasi IN ('koordinator','laz','kemenag')),
  id_koordinator bigint REFERENCES koordinator_beasiswa ON DELETE RESTRICT,
  id_pengelola_laz bigint REFERENCES pengelola_lembaga_zakat ON DELETE RESTRICT,
  id_pengelola_kemenag bigint REFERENCES pengelola_kemenag ON DELETE RESTRICT,
  waktu_verifikasi timestamptz NOT NULL DEFAULT waktu_sekarang(),
  hasil_verifikasi text NOT NULL CHECK (hasil_verifikasi IN ('disetujui','perlu_revisi')),
  catatan_verifikasi text,
  CHECK ((tahap_verifikasi='koordinator' AND id_koordinator IS NOT NULL AND id_pengelola_laz IS NULL AND id_pengelola_kemenag IS NULL)
    OR (tahap_verifikasi='laz' AND id_koordinator IS NULL AND id_pengelola_laz IS NOT NULL AND id_pengelola_kemenag IS NULL)
    OR (tahap_verifikasi='kemenag' AND id_koordinator IS NULL AND id_pengelola_laz IS NULL AND id_pengelola_kemenag IS NOT NULL)),
  CHECK (hasil_verifikasi<>'perlu_revisi' OR coalesce(btrim(catatan_verifikasi),'')<>''),
  UNIQUE (id_laporan_bulanan,nomor_pengajuan,tahap_verifikasi),
  FOREIGN KEY (id_laporan_bulanan,nomor_pengajuan) REFERENCES pengajuan_laporan ON DELETE RESTRICT
);
CREATE VIEW v_status_laporan AS
SELECT l.id_laporan_bulanan, coalesce(p.nomor_pengajuan,0) AS nomor_pengajuan,
  p.waktu_pengumpulan,
  EXISTS (SELECT 1 FROM pengajuan_laporan s WHERE s.id_laporan_bulanan=l.id_laporan_bulanan) AS kewajiban_pengumpulan_terpenuhi,
  CASE WHEN p.nomor_pengajuan IS NULL THEN 'draf'
    WHEN EXISTS (SELECT 1 FROM verifikasi_laporan v WHERE v.id_laporan_bulanan=l.id_laporan_bulanan AND v.nomor_pengajuan=p.nomor_pengajuan AND v.hasil_verifikasi='perlu_revisi') THEN 'perlu_revisi'
    WHEN (SELECT count(*) FROM verifikasi_laporan v WHERE v.id_laporan_bulanan=l.id_laporan_bulanan AND v.nomor_pengajuan=p.nomor_pengajuan AND v.hasil_verifikasi='disetujui')=3 THEN 'disetujui'
    ELSE 'diajukan' END AS status_pengisian
FROM laporan_bulanan l
LEFT JOIN LATERAL (SELECT * FROM pengajuan_laporan s WHERE s.id_laporan_bulanan=l.id_laporan_bulanan ORDER BY nomor_pengajuan DESC LIMIT 1) p ON true;

CREATE FUNCTION laporan_bisa_diubah(p_id bigint) RETURNS boolean
LANGUAGE sql STABLE SET search_path = sim_bezakat, pg_catalog AS $$
SELECT coalesce((SELECT status_pengisian IN ('draf','perlu_revisi') FROM v_status_laporan WHERE id_laporan_bulanan=p_id),false)
$$;
CREATE FUNCTION jaga_laporan() RETURNS trigger
LANGUAGE plpgsql SET search_path = sim_bezakat, pg_catalog AS $$
BEGIN
  IF TG_OP='UPDATE' THEN
    IF (NEW.id_laporan_bulanan,NEW.id_awardee,NEW.id_periode_monitoring,NEW.id_evaluasi_progres,NEW.id_lpj_keuangan,NEW.dibuat_pada)
      IS DISTINCT FROM (OLD.id_laporan_bulanan,OLD.id_awardee,OLD.id_periode_monitoring,OLD.id_evaluasi_progres,OLD.id_lpj_keuangan,OLD.dibuat_pada) THEN
      RAISE EXCEPTION 'Identitas laporan tidak dapat dipindahkan' USING ERRCODE='23514'; END IF;
    IF NOT laporan_bisa_diubah(OLD.id_laporan_bulanan) THEN
      RAISE EXCEPTION 'Laporan terkirim hanya bisa diubah setelah diminta revisi' USING ERRCODE='23514'; END IF;
    RETURN NEW;
  END IF;
  IF EXISTS (SELECT 1 FROM pengajuan_laporan WHERE id_laporan_bulanan=OLD.id_laporan_bulanan) THEN
    RAISE EXCEPTION 'Laporan yang pernah diajukan tidak boleh dihapus' USING ERRCODE='23514'; END IF;
  RETURN OLD;
END $$;
CREATE TRIGGER laporan_terjaga BEFORE UPDATE OR DELETE ON laporan_bulanan FOR EACH ROW EXECUTE FUNCTION jaga_laporan();

CREATE FUNCTION siapkan_berkas_keuangan() RETURNS trigger
LANGUAGE plpgsql SET search_path = sim_bezakat, pg_catalog AS $$
DECLARE pemilik bigint;
BEGIN
  SELECT id_awardee INTO pemilik FROM laporan_bulanan WHERE id_laporan_bulanan=NEW.id_laporan_bulanan FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Laporan tidak ada' USING ERRCODE='23503'; END IF;
  IF pemilik<>NEW.diunggah_oleh OR NOT laporan_bisa_diubah(NEW.id_laporan_bulanan) THEN
    RAISE EXCEPTION 'Pemilik/status laporan tidak mengizinkan unggahan' USING ERRCODE='23514'; END IF;
  SELECT coalesce(max(versi),0)+1 INTO NEW.versi FROM berkas_keuangan_versi
    WHERE id_laporan_bulanan=NEW.id_laporan_bulanan AND jenis_dokumen=NEW.jenis_dokumen;
  NEW.diunggah_pada:=waktu_sekarang();
  RETURN NEW;
END $$;
CREATE TRIGGER berkas_nomor BEFORE INSERT ON berkas_keuangan_versi FOR EACH ROW EXECUTE FUNCTION siapkan_berkas_keuangan();
CREATE TRIGGER berkas_tetap BEFORE UPDATE OR DELETE ON berkas_keuangan_versi FOR EACH ROW EXECUTE FUNCTION tolak_perubahan();

CREATE FUNCTION siapkan_pengajuan() RETURNS trigger
LANGUAGE plpgsql SET search_path = sim_bezakat, pg_catalog AS $$
DECLARE l laporan_bulanan; p periode_monitoring; a awardee; s v_status_laporan; w timestamptz;
BEGIN
  SELECT * INTO l FROM laporan_bulanan WHERE id_laporan_bulanan=NEW.id_laporan_bulanan FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Laporan tidak ada' USING ERRCODE='23503'; END IF;
  SELECT * INTO s FROM v_status_laporan WHERE id_laporan_bulanan=l.id_laporan_bulanan;
  SELECT * INTO a FROM awardee WHERE id_awardee=l.id_awardee;
  SELECT * INTO p FROM periode_monitoring WHERE id_periode_monitoring=l.id_periode_monitoring;
  w:=waktu_sekarang();
  IF NEW.diajukan_oleh<>l.id_awardee THEN RAISE EXCEPTION 'Pengaju bukan pemilik' USING ERRCODE='23514'; END IF;
  IF NOT EXISTS (SELECT 1 FROM akun_pengguna WHERE id_akun=l.id_awardee AND status_aktif) THEN
    RAISE EXCEPTION 'Akun tidak aktif' USING ERRCODE='23514'; END IF;
  IF s.nomor_pengajuan=0 THEN
    IF w<p.tanggal_buka OR w>=p.tanggal_tenggat_cutoff THEN
      RAISE EXCEPTION 'Pengajuan pertama di luar periode WIB' USING ERRCODE='23514'; END IF;
  ELSIF s.status_pengisian<>'perlu_revisi' THEN
    RAISE EXCEPTION 'Pengajuan ulang membutuhkan permintaan revisi' USING ERRCODE='23514';
  ELSIF coalesce(btrim(NEW.catatan_perbaikan),'')='' THEN
    RAISE EXCEPTION 'Catatan perbaikan wajib diisi' USING ERRCODE='23514';
  END IF;
  IF coalesce(btrim(l.ringkasan_refleksi_diri),'')='' OR l.poin_sholat_berjamaah IS NULL
    OR l.frekuensi_qiyamullail IS NULL OR coalesce(btrim(l.hafalan_quran),'')=''
    OR l.skor_adaptasi_belajar IS NULL OR l.skor_kelola_stres IS NULL THEN
    RAISE EXCEPTION 'Evaluasi dan ringkasan laporan belum lengkap' USING ERRCODE='23514'; END IF;
  IF NOT EXISTS (SELECT 1 FROM berkas_keuangan_versi WHERE id_laporan_bulanan=l.id_laporan_bulanan AND jenis_dokumen='periode_berjalan') THEN
    RAISE EXCEPTION 'Berkas keuangan periode berjalan wajib dilampirkan' USING ERRCODE='23514'; END IF;
  NEW.nomor_pengajuan:=s.nomor_pengajuan+1;
  NEW.waktu_pengumpulan:=w;
  NEW.snapshot_laporan:=to_jsonb(l) || jsonb_build_object(
    'realisasi_pengeluaran',(SELECT coalesce(jsonb_agg(to_jsonb(r) ORDER BY id_realisasi_pengeluaran),'[]') FROM realisasi_pengeluaran r WHERE r.id_lpj_keuangan=l.id_lpj_keuangan),
    'prestasi',(SELECT coalesce(jsonb_agg(to_jsonb(r) ORDER BY id_prestasi),'[]') FROM prestasi r WHERE r.id_awardee=l.id_awardee AND r.id_periode_monitoring=l.id_periode_monitoring));
  NEW.snapshot_profil:=to_jsonb(a);
  RETURN NEW;
END $$;
