SELECT p.*, CASE WHEN waktu_sekarang()<tanggal_buka THEN 'belum_dibuka'
                WHEN waktu_sekarang()<tanggal_tenggat_cutoff THEN 'dibuka' ELSE 'ditutup' END AS status_periode
FROM periode_monitoring p;

