CREATE FUNCTION isi_tanggal_periode() RETURNS trigger
LANGUAGE plpgsql SET search_path = sim_bezakat, pg_catalog AS $$
BEGIN
  NEW.tanggal_awal_laporan:=make_date(NEW.tahun_anggaran,NEW.bulan,1);
  NEW.tanggal_akhir_laporan:=(NEW.tanggal_awal_laporan+interval '1 month - 1 day')::date;
  NEW.tanggal_buka:=make_date(NEW.tahun_anggaran,NEW.bulan,10)::timestamp AT TIME ZONE 'Asia/Jakarta';
  NEW.tanggal_tenggat_cutoff:=(make_date(NEW.tahun_anggaran,NEW.bulan,10)+interval '1 month') AT TIME ZONE 'Asia/Jakarta';
  RETURN NEW;
END $$;
CREATE TRIGGER periode_tanggal BEFORE INSERT ON periode_monitoring FOR EACH ROW EXECUTE FUNCTION isi_tanggal_periode();
