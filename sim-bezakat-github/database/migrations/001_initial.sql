-- Total/disjoint: FK komposit menegakkan jenis subclass; trigger deferred
-- memastikan akun memiliki tepat satu profil dan awardee memiliki wali saat COMMIT.
CREATE FUNCTION cek_profil_akun() RETURNS trigger
LANGUAGE plpgsql SET search_path = sim_bezakat, pg_catalog AS $$
DECLARE a bigint; r text; jumlah integer;
BEGIN
  IF TG_TABLE_NAME='akun_pengguna' THEN a:=NEW.id_akun;
  ELSE a:=(to_jsonb(OLD)->>TG_ARGV[0])::bigint; END IF;
  SELECT peran INTO r FROM akun_pengguna WHERE id_akun=a FOR UPDATE;
  IF NOT FOUND THEN RETURN NULL; END IF;
  SELECT (SELECT count(*) FROM awardee WHERE id_awardee=a)
       + (SELECT count(*) FROM koordinator_beasiswa WHERE id_koordinator=a)
       + (SELECT count(*) FROM pengelola_kemenag WHERE id_pengelola_kemenag=a)
       + (SELECT count(*) FROM pengelola_lembaga_zakat WHERE id_pengelola_laz=a) INTO jumlah;
  IF jumlah<>1 THEN RAISE EXCEPTION 'Akun % harus memiliki tepat satu profil peran',a USING ERRCODE='23514'; END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER akun_total AFTER INSERT OR UPDATE ON akun_pengguna
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION cek_profil_akun();
CREATE CONSTRAINT TRIGGER awardee_total AFTER DELETE OR UPDATE ON awardee
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION cek_profil_akun('id_awardee');
CREATE CONSTRAINT TRIGGER koordinator_total AFTER DELETE OR UPDATE ON koordinator_beasiswa
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION cek_profil_akun('id_koordinator');
CREATE CONSTRAINT TRIGGER laz_total AFTER DELETE OR UPDATE ON pengelola_lembaga_zakat
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION cek_profil_akun('id_pengelola_laz');
CREATE CONSTRAINT TRIGGER kemenag_total AFTER DELETE OR UPDATE ON pengelola_kemenag
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION cek_profil_akun('id_pengelola_kemenag');
CREATE FUNCTION cek_wali() RETURNS trigger
LANGUAGE plpgsql SET search_path = sim_bezakat, pg_catalog AS $$
DECLARE a bigint;
BEGIN
  a:=CASE WHEN TG_OP='DELETE' THEN OLD.id_awardee ELSE NEW.id_awardee END;
  -- Serialize concurrent removals of different contacts of the same awardee.
  PERFORM 1 FROM awardee WHERE id_awardee=a FOR UPDATE;
  IF EXISTS (SELECT 1 FROM awardee WHERE id_awardee=a)
     AND NOT EXISTS (SELECT 1 FROM kontak_wali WHERE id_awardee=a) THEN
    RAISE EXCEPTION 'Awardee % membutuhkan minimal satu kontak wali',a USING ERRCODE='23514';
  END IF;
  IF TG_OP='UPDATE' AND OLD.id_awardee<>NEW.id_awardee
     AND EXISTS (SELECT 1 FROM awardee WHERE id_awardee=OLD.id_awardee)
     AND NOT EXISTS (SELECT 1 FROM kontak_wali WHERE id_awardee=OLD.id_awardee) THEN
    RAISE EXCEPTION 'Kontak wali terakhir tidak boleh dipindahkan' USING ERRCODE='23514';
  END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER awardee_wajib_wali AFTER INSERT OR UPDATE ON awardee
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION cek_wali();
CREATE CONSTRAINT TRIGGER wali_wajib_ada AFTER DELETE OR UPDATE ON kontak_wali
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION cek_wali();

