CREATE FUNCTION cek_verifikasi_laporan() RETURNS trigger
LANGUAGE plpgsql SET search_path = sim_bezakat, pg_catalog AS $$
DECLARE l laporan_bulanan; a awardee; s v_status_laporan; pelaksana bigint; tahap_sebelum text;
BEGIN
  SELECT * INTO l FROM laporan_bulanan WHERE id_laporan_bulanan=NEW.id_laporan_bulanan FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Laporan tidak ada' USING ERRCODE='23503'; END IF;
  SELECT * INTO a FROM awardee WHERE id_awardee=l.id_awardee;
  SELECT * INTO s FROM v_status_laporan WHERE id_laporan_bulanan=l.id_laporan_bulanan;
  IF NEW.nomor_pengajuan<>s.nomor_pengajuan OR s.status_pengisian<>'diajukan' THEN
    RAISE EXCEPTION 'Hanya pengajuan terbaru yang menunggu pemeriksaan dapat diverifikasi' USING ERRCODE='23514'; END IF;
  pelaksana:=coalesce(NEW.id_koordinator,NEW.id_pengelola_laz,NEW.id_pengelola_kemenag);
  IF NOT EXISTS (SELECT 1 FROM akun_pengguna WHERE id_akun=pelaksana AND status_aktif AND peran=NEW.tahap_verifikasi) THEN
    RAISE EXCEPTION 'Peran pelaksana tidak sesuai/tidak aktif' USING ERRCODE='23514'; END IF;
  IF NEW.tahap_verifikasi='koordinator' AND NEW.id_koordinator IS DISTINCT FROM a.id_koordinator THEN
    RAISE EXCEPTION 'Awardee bukan binaan koordinator' USING ERRCODE='23514'; END IF;
  IF NEW.tahap_verifikasi='laz' AND NOT EXISTS (SELECT 1 FROM pengelola_lembaga_zakat WHERE id_pengelola_laz=NEW.id_pengelola_laz AND id_lembaga=a.id_lembaga) THEN
    RAISE EXCEPTION 'Awardee bukan anggota LAZ pelaksana' USING ERRCODE='23514'; END IF;
  tahap_sebelum:=CASE NEW.tahap_verifikasi WHEN 'laz' THEN 'koordinator' WHEN 'kemenag' THEN 'laz' END;
  IF tahap_sebelum IS NOT NULL AND NOT EXISTS (SELECT 1 FROM verifikasi_laporan WHERE id_laporan_bulanan=l.id_laporan_bulanan AND nomor_pengajuan=NEW.nomor_pengajuan AND tahap_verifikasi=tahap_sebelum AND hasil_verifikasi='disetujui') THEN
    RAISE EXCEPTION 'Tahap sebelumnya belum disetujui pada pengajuan yang sama' USING ERRCODE='23514'; END IF;
  NEW.waktu_verifikasi:=waktu_sekarang();
  RETURN NEW;
END $$;
CREATE TRIGGER verifikasi_valid BEFORE INSERT ON verifikasi_laporan FOR EACH ROW EXECUTE FUNCTION cek_verifikasi_laporan();
