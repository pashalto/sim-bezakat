CREATE FUNCTION evaluasi_beasiswa() RETURNS trigger
LANGUAGE plpgsql SET search_path = sim_bezakat, pg_catalog AS $$
DECLARE pemilik bigint; lama text; baru text;
BEGIN
  IF NEW.hasil_verifikasi<>'terverifikasi' THEN RETURN NULL; END IF;
  SELECT r.id_awardee INTO pemilik FROM versi_akademik v JOIN riwayat_akademik r USING(id_riwayat_akademik) WHERE v.id_versi_akademik=NEW.id_versi_akademik;
  SELECT status_awardee INTO lama FROM awardee WHERE id_awardee=pemilik FOR UPDATE;
  baru:=lama;
  IF EXISTS (SELECT 1 FROM v_akademik_terverifikasi a JOIN v_akademik_terverifikasi b
    ON b.id_awardee=a.id_awardee AND b.semester_ke=a.semester_ke+1
    WHERE a.id_awardee=pemilik AND a.ips<3.00 AND b.ips<3.00) THEN baru:='nonaktif';
  ELSIF lama='aktif' AND EXISTS (SELECT 1 FROM v_akademik_terverifikasi WHERE id_awardee=pemilik AND ips<3.00) THEN baru:='evaluasi';
  END IF;
  IF baru<>lama THEN
    UPDATE awardee SET status_awardee=baru WHERE id_awardee=pemilik;
    INSERT INTO riwayat_status_beasiswa(id_awardee,status_sebelum,status_sesudah,id_verifikasi_akademik,alasan)
    VALUES(pemilik,lama,baru,NEW.id_verifikasi_akademik,
      CASE WHEN baru='nonaktif' THEN 'Dua semester berturut-turut memiliki IPS terverifikasi di bawah 3,00' ELSE 'IPS terverifikasi di bawah 3,00' END);
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER akademik_evaluasi AFTER INSERT ON verifikasi_akademik FOR EACH ROW EXECUTE FUNCTION evaluasi_beasiswa();
CREATE FUNCTION jaga_status_awardee() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP='INSERT' AND NEW.status_awardee<>'aktif' THEN
    RAISE EXCEPTION 'Status awal beasiswa harus aktif' USING ERRCODE='23514'; END IF;
  IF TG_OP='UPDATE' AND NEW.status_awardee<>OLD.status_awardee AND pg_trigger_depth()<2 THEN
    RAISE EXCEPTION 'Status beasiswa dikelola oleh hasil verifikasi akademik' USING ERRCODE='23514'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER status_awardee_terjaga BEFORE INSERT OR UPDATE ON awardee FOR EACH ROW EXECUTE FUNCTION jaga_status_awardee();

