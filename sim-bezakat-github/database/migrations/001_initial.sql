-- Entri pengeluaran manual juga mengikuti kunci laporan; jangan mengubah FK
-- untuk memindahkan detail dari laporan terkirim ke draf.
CREATE FUNCTION jaga_realisasi() RETURNS trigger
LANGUAGE plpgsql SET search_path = sim_bezakat, pg_catalog AS $$
DECLARE lpj bigint; lap bigint;
BEGIN
  lpj:=CASE WHEN TG_OP='DELETE' THEN OLD.id_lpj_keuangan ELSE NEW.id_lpj_keuangan END;
  IF TG_OP='UPDATE' AND NEW.id_lpj_keuangan<>OLD.id_lpj_keuangan THEN
    RAISE EXCEPTION 'Pengeluaran tidak dapat dipindahkan' USING ERRCODE='23514'; END IF;
  SELECT id_laporan_bulanan INTO lap FROM laporan_bulanan WHERE id_lpj_keuangan=lpj FOR UPDATE;
  IF lap IS NOT NULL AND NOT laporan_bisa_diubah(lap) THEN RAISE EXCEPTION 'Laporan terkunci' USING ERRCODE='23514'; END IF;
  IF TG_OP='DELETE' THEN RETURN OLD; END IF; RETURN NEW;
END $$;
CREATE TRIGGER realisasi_terjaga BEFORE INSERT OR UPDATE OR DELETE ON realisasi_pengeluaran FOR EACH ROW EXECUTE FUNCTION jaga_realisasi();

CREATE TABLE riwayat_akademik (
  id_riwayat_akademik bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_awardee bigint NOT NULL REFERENCES awardee ON DELETE RESTRICT,
  semester_ke integer NOT NULL CHECK (semester_ke>=1),
  UNIQUE (id_awardee,semester_ke)
);
CREATE TABLE versi_akademik (
  id_versi_akademik bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_riwayat_akademik bigint NOT NULL REFERENCES riwayat_akademik ON DELETE RESTRICT,
  versi integer NOT NULL CHECK (versi>0),
  ips numeric(3,2) NOT NULL CHECK (ips BETWEEN 0 AND 4),
  ipk_kumulatif numeric(3,2) NOT NULL CHECK (ipk_kumulatif BETWEEN 0 AND 4),
  nama_berkas_khs text NOT NULL CHECK (lower(nama_berkas_khs) LIKE '%.pdf'),
  mime_type text NOT NULL DEFAULT 'application/pdf' CHECK (mime_type='application/pdf'),
  ukuran_byte bigint NOT NULL CHECK (ukuran_byte>0),
  tautan_berkas_khs lokasi_berkas NOT NULL UNIQUE,
  sha256 text CHECK (sha256 ~ '^[a-f0-9]{64}$'),
  diajukan_oleh bigint NOT NULL REFERENCES awardee ON DELETE RESTRICT,
  diajukan_pada timestamptz NOT NULL DEFAULT waktu_sekarang(),
  UNIQUE (id_riwayat_akademik,versi)
);
CREATE TABLE verifikasi_akademik (
  id_verifikasi_akademik bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_versi_akademik bigint NOT NULL UNIQUE REFERENCES versi_akademik ON DELETE RESTRICT,
  id_koordinator bigint NOT NULL REFERENCES koordinator_beasiswa ON DELETE RESTRICT,
  hasil_verifikasi text NOT NULL CHECK (hasil_verifikasi IN ('terverifikasi','perlu_revisi')),
  catatan_pembinaan text,
  waktu_verifikasi timestamptz NOT NULL DEFAULT waktu_sekarang(),
  CHECK (hasil_verifikasi<>'perlu_revisi' OR coalesce(btrim(catatan_pembinaan),'')<>'')
);
CREATE TABLE riwayat_status_beasiswa (
  id_riwayat_status bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_awardee bigint NOT NULL REFERENCES awardee ON DELETE RESTRICT,
  status_sebelum text NOT NULL CHECK (status_sebelum IN ('aktif','evaluasi','nonaktif')),
  status_sesudah text NOT NULL CHECK (status_sesudah IN ('aktif','evaluasi','nonaktif')),
  id_verifikasi_akademik bigint NOT NULL REFERENCES verifikasi_akademik ON DELETE RESTRICT,
  alasan text NOT NULL,
  waktu_perubahan timestamptz NOT NULL DEFAULT waktu_sekarang(),
  CHECK (status_sebelum<>status_sesudah)
);
CREATE VIEW v_akademik_terverifikasi AS
SELECT r.*, a.id_versi_akademik,a.versi,a.ips,a.ipk_kumulatif,a.tautan_berkas_khs,
       v.id_verifikasi_akademik,v.waktu_verifikasi,v.catatan_pembinaan,
       CASE WHEN a.ips<3.00 THEN 'peringatan_ips' ELSE 'memenuhi' END AS status_evaluasi_ips
FROM riwayat_akademik r
JOIN LATERAL (SELECT a.* FROM versi_akademik a JOIN verifikasi_akademik v USING(id_versi_akademik)
  WHERE a.id_riwayat_akademik=r.id_riwayat_akademik AND v.hasil_verifikasi='terverifikasi'
  ORDER BY a.versi DESC LIMIT 1) a ON true
JOIN verifikasi_akademik v USING(id_versi_akademik);

CREATE FUNCTION siapkan_akademik() RETURNS trigger
LANGUAGE plpgsql SET search_path = sim_bezakat, pg_catalog AS $$
DECLARE pemilik bigint;
BEGIN
  SELECT id_awardee INTO pemilik FROM riwayat_akademik WHERE id_riwayat_akademik=NEW.id_riwayat_akademik FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Semester tidak ada' USING ERRCODE='23503'; END IF;
  IF NEW.diajukan_oleh<>pemilik OR NOT EXISTS (SELECT 1 FROM akun_pengguna WHERE id_akun=pemilik AND status_aktif) THEN
    RAISE EXCEPTION 'Pengaju akademik bukan pemilik aktif' USING ERRCODE='23514'; END IF;
  SELECT coalesce(max(versi),0)+1 INTO NEW.versi FROM versi_akademik WHERE id_riwayat_akademik=NEW.id_riwayat_akademik;
  NEW.diajukan_pada:=waktu_sekarang();
  RETURN NEW;
END $$;
