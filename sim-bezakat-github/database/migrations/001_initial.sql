CREATE FUNCTION cek_verifikasi_akademik() RETURNS trigger
LANGUAGE plpgsql SET search_path = sim_bezakat, pg_catalog AS $$
DECLARE a awardee; semester_id bigint; versi_baru integer;
BEGIN
  SELECT aw.* INTO a FROM versi_akademik va JOIN riwayat_akademik r USING(id_riwayat_akademik)
    JOIN awardee aw USING(id_awardee) WHERE va.id_versi_akademik=NEW.id_versi_akademik FOR UPDATE OF aw;
  IF NOT FOUND THEN RAISE EXCEPTION 'Versi akademik tidak ada' USING ERRCODE='23503'; END IF;
  SELECT id_riwayat_akademik,versi INTO semester_id,versi_baru FROM versi_akademik WHERE id_versi_akademik=NEW.id_versi_akademik;
  PERFORM 1 FROM riwayat_akademik WHERE id_riwayat_akademik=semester_id FOR UPDATE;
  IF versi_baru<>(SELECT max(versi) FROM versi_akademik WHERE id_riwayat_akademik=semester_id) THEN
    RAISE EXCEPTION 'Verifikasi harus memakai versi akademik terbaru' USING ERRCODE='23514'; END IF;
  IF NEW.id_koordinator<>a.id_koordinator OR NOT EXISTS (SELECT 1 FROM akun_pengguna WHERE id_akun=NEW.id_koordinator AND status_aktif) THEN
    RAISE EXCEPTION 'Koordinator akademik tidak berwenang' USING ERRCODE='23514'; END IF;
  NEW.waktu_verifikasi:=waktu_sekarang();
  RETURN NEW;
END $$;
